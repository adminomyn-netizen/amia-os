-- Hạn thẻ = ngày bắt đầu + N tháng (theo lịch, 31/01 + 1 tháng = 28 hoặc 29/02) + M ngày. Trả null khi không có hạn.
create or replace function public.tinh_han_the(p_thang integer, p_ngay integer, p_tu date)
returns date language sql immutable as $$
  select case when p_tu is null or (coalesce(p_thang, 0) <= 0 and coalesce(p_ngay, 0) <= 0) then null
              else (p_tu + make_interval(months => greatest(coalesce(p_thang, 0), 0)))::date + greatest(coalesce(p_ngay, 0), 0) end
$$;

