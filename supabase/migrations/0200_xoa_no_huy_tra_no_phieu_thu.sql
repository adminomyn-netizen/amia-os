comment on column public.thanh_toan.dao_cua_id is 'Dòng hoàn này huỷ (đảo) lần trả nợ nào. Mỗi lần trả nợ chỉ đảo được một lần.';

-- ── Xoá nợ (điều chỉnh nợ) ──
alter table public.hoa_don add column no_da_xoa bigint not null default 0;
comment on column public.hoa_don.no_da_xoa is 'Tổng nợ đã xoá (điều chỉnh nợ) trừ phần đã huỷ; con_no = tong_phai_thu − da_thu − no_da_xoa.';

create table public.hoa_don_dieu_chinh_no (
  id bigint generated always as identity primary key,
  hoa_don_id uuid not null references public.hoa_don (id),
  loai text not null check (loai in ('xoa_no', 'huy_xoa_no')),
  so_tien bigint not null check (so_tien > 0),
  ly_do text not null check (char_length(btrim(ly_do)) between 1 and 500),
  dao_cua_id bigint references public.hoa_don_dieu_chinh_no (id),
  nguoi_id uuid not null references public.nhan_vien (id),
  ngay date not null default ((now() at time zone 'Asia/Ho_Chi_Minh')::date),
  tao_luc timestamptz not null default now(),
  check ((loai = 'huy_xoa_no') = (dao_cua_id is not null))
);
create index hoa_don_dieu_chinh_no_hd_idx on public.hoa_don_dieu_chinh_no (hoa_don_id);
create unique index hoa_don_dieu_chinh_no_dao_uq on public.hoa_don_dieu_chinh_no (dao_cua_id) where dao_cua_id is not null;
create trigger hoa_don_dieu_chinh_no_chi_them before update or delete on public.hoa_don_dieu_chinh_no
  for each row execute function public.chi_them_dong();

-- Tính lại hoá đơn: trừ thêm nợ đã xoá.
create or replace function public.tinh_lai_hoa_don(p_id uuid)
 returns void language plpgsql set search_path to 'public', 'pg_temp'
as $function$
declare h public.hoa_don; v_hang bigint; v_vat bigint; v_thu bigint; v_phai bigint; v_xoa bigint;
begin
  select * into h from public.hoa_don where id = p_id;
  if not found then return; end if;
  if h.la_so_du_dau or h.la_lich_su then
    v_hang := h.tong_hang; v_vat := h.vat_tien; v_phai := h.tong_phai_thu;
  else
    select coalesce(sum(thanh_tien), 0) into v_hang from public.hoa_don_dong where hoa_don_id = p_id;
    v_vat := round((greatest(v_hang - h.giam_gia_don, 0)) * h.vat_pct / 100.0)::bigint;
    v_phai := greatest(v_hang - h.giam_gia_don, 0) + v_vat + h.phu_phi + h.tip;
  end if;
  select coalesce(sum(case loai when 'thu' then so_tien else -so_tien end), 0) into v_thu from public.thanh_toan where hoa_don_id = p_id;
  select coalesce(sum(case loai when 'xoa_no' then so_tien else -so_tien end), 0) into v_xoa from public.hoa_don_dieu_chinh_no where hoa_don_id = p_id;
  update public.hoa_don set tong_hang = v_hang, vat_tien = v_vat, tong_phai_thu = v_phai, da_thu = v_thu, no_da_xoa = v_xoa, con_no = v_phai - v_thu - v_xoa where id = p_id;
end $function$;

-- Thu không vượt phần còn nợ (đã trừ nợ đã xoá).
create or replace function public.trg_thanh_toan_truoc()
 returns trigger language plpgsql set search_path to 'public', 'pg_temp'
as $function$
declare h public.hoa_don; t public.the_khach; v_du bigint;
begin
  select * into h from public.hoa_don where id = new.hoa_don_id for update;
  if not found then raise exception 'Không có hoá đơn này' using errcode = 'P0001'; end if;
  if h.la_lich_su then new.la_lich_su := true; return new; end if;
  if h.trang_thai = 'huy' then raise exception 'Hoá đơn đã huỷ, không ghi thanh toán được' using errcode = 'P0001'; end if;
  if new.loai = 'thu' then
    if new.so_tien > h.tong_phai_thu - h.da_thu - h.no_da_xoa then
      raise exception 'Số thu % vượt phần còn phải thu % của hoá đơn %', new.so_tien, h.tong_phai_thu - h.da_thu - h.no_da_xoa, h.ma using errcode = 'P0001';
    end if;
  else
    if new.so_tien > h.da_thu then raise exception 'Hoàn vượt số đã thu của hoá đơn %', h.ma using errcode = 'P0001'; end if;
  end if;
  if new.phuong_thuc = 'the_tien' then
    if new.the_id is null then raise exception 'Trả bằng thẻ tiền phải chọn thẻ' using errcode = 'P0001'; end if;
    select * into t from public.the_khach where id = new.the_id for update;
    if not found or t.loai <> 'tien' then raise exception 'Đây không phải thẻ tiền' using errcode = 'P0001'; end if;
    if t.khach_id is distinct from h.khach_id then raise exception 'Thẻ không thuộc khách của hoá đơn' using errcode = 'P0001'; end if;
    if new.loai = 'thu' then
      if t.trang_thai <> 'hoat_dong' then raise exception 'Thẻ tiền đang bị khoá hoặc thu hồi' using errcode = 'P0001'; end if;
      if t.han_dung is not null and t.han_dung < new.ngay then raise exception 'Thẻ tiền đã hết hạn' using errcode = 'P0001'; end if;
      select coalesce(sum(so_tien), 0) into v_du from public.the_so_cai where the_id = t.id;
      if v_du < new.so_tien then raise exception 'Thẻ tiền chỉ còn % đ, không đủ trừ %', v_du, new.so_tien using errcode = 'P0001'; end if;
    end if;
  elsif new.the_id is not null then
    raise exception 'Chỉ thanh toán bằng thẻ tiền mới gắn thẻ' using errcode = 'P0001';
  end if;
  return new;
end $function$;

-- Lịch sử nợ của một hoá đơn (như hộp "Nợ của khách"): các lần trả nợ (thu SAU khi chốt đơn, không tính thẻ tiền) và các lần xoá nợ, kèm dòng đã bị huỷ.
-- la_cuoi = dòng cuối còn hiệu lực (chỉ dòng này được "Huỷ").
create or replace function public.lich_su_no_hoa_don(p_id uuid)
returns table (loai text, ref text, so_phieu bigint, ngay date, so_tien bigint, phuong_thuc text, ngan_hang text, loai_vi text, ly_do text, nguoi_id uuid, tao_luc timestamptz, da_huy boolean, la_cuoi boolean)
language sql stable set search_path to 'public', 'pg_temp' as $$
  with h as (select * from public.hoa_don where id = p_id),
  l as (
    select 'tra_no'::text as loai, t.id::text as ref, t.so_phieu, t.ngay, t.so_tien, t.phuong_thuc, t.ngan_hang, t.loai_vi, t.ghi_chu as ly_do, t.nguoi_id, t.tao_luc,
           exists (select 1 from public.thanh_toan d where d.dao_cua_id = t.id) as da_huy
      from public.thanh_toan t, h
     where t.hoa_don_id = h.id and t.loai = 'thu' and t.phuong_thuc <> 'the_tien' and t.dao_cua_id is null
       and ((h.chot_luc is not null and t.tao_luc > h.chot_luc) or t.ngay > h.ngay_hd)
    union all
    select 'xoa_no', c.id::text, null, c.ngay, c.so_tien, null, null, null, c.ly_do, c.nguoi_id, c.tao_luc,
           exists (select 1 from public.hoa_don_dieu_chinh_no d where d.dao_cua_id = c.id)
      from public.hoa_don_dieu_chinh_no c where c.hoa_don_id = p_id and c.loai = 'xoa_no')
  select l.*, (not l.da_huy and row_number() over (partition by l.da_huy order by l.tao_luc desc, l.ref desc) = 1) as la_cuoi
    from l order by l.tao_luc desc, l.ref desc
$$;
revoke all on function public.lich_su_no_hoa_don(uuid) from public, anon, authenticated;

-- Điều chỉnh nợ (xoá nợ): số nợ mới phải nhỏ hơn nợ hiện tại, bắt lý do. Quyền (chỉ Chủ) kiểm ở máy chủ app trước khi gọi.
create or replace function public.dieu_chinh_no(p_id uuid, p_no_moi bigint, p_ly_do text, p_nguoi uuid)
returns bigint language plpgsql set search_path to 'public', 'pg_temp' as $$
declare h public.hoa_don; v_id bigint;
begin
  if coalesce(btrim(p_ly_do), '') = '' then raise exception 'Điều chỉnh nợ phải ghi lý do' using errcode = 'P0001'; end if;
  select * into h from public.hoa_don where id = p_id for update;
  if not found then raise exception 'Không có hoá đơn này' using errcode = 'P0001'; end if;
  if h.trang_thai <> 'hoan_thanh' then raise exception 'Chỉ điều chỉnh nợ hoá đơn đã hoàn thành' using errcode = 'P0001'; end if;
  if h.la_lich_su then raise exception 'Hoá đơn % chuyển từ SalonHero (còn đồng bộ tới 15/11): điều chỉnh nợ ở SalonHero', coalesce(h.sh_ma, h.ma) using errcode = 'P0001'; end if;
  if h.con_no <= 0 then raise exception 'Hoá đơn % không còn nợ', h.ma using errcode = 'P0001'; end if;
  if p_no_moi is null or p_no_moi < 0 or p_no_moi >= h.con_no then
    raise exception 'Số nợ mới phải từ 0 đến nhỏ hơn nợ hiện tại %', h.con_no using errcode = 'P0001';
  end if;
  insert into public.hoa_don_dieu_chinh_no (hoa_don_id, loai, so_tien, ly_do, nguoi_id) values (p_id, 'xoa_no', h.con_no - p_no_moi, btrim(p_ly_do), p_nguoi) returning id into v_id;
  perform public.tinh_lai_hoa_don(p_id);
  return v_id;
end $$;
revoke all on function public.dieu_chinh_no(uuid, bigint, text, uuid) from public, anon, authenticated;

-- Huỷ lần trả nợ / lần xoá nợ: CHỈ dòng cuối còn hiệu lực của lịch sử nợ (p_ref phải đúng dòng đó, chặn bấm trên màn hình cũ).
create or replace function public.huy_lan_tra_no(p_id uuid, p_ref text, p_nguoi uuid, p_ly_do text default null)
returns void language plpgsql set search_path to 'public', 'pg_temp' as $$
declare h public.hoa_don; c record; t public.thanh_toan; x public.hoa_don_dieu_chinh_no;
begin
  select * into h from public.hoa_don where id = p_id for update;
  if not found then raise exception 'Không có hoá đơn này' using errcode = 'P0001'; end if;
  if h.trang_thai <> 'hoan_thanh' then raise exception 'Chỉ huỷ lần trả nợ của hoá đơn đã hoàn thành' using errcode = 'P0001'; end if;
  if h.la_lich_su then raise exception 'Hoá đơn % chuyển từ SalonHero (còn đồng bộ tới 15/11): huỷ trả nợ ở SalonHero', coalesce(h.sh_ma, h.ma) using errcode = 'P0001'; end if;
  select * into c from public.lich_su_no_hoa_don(p_id) where la_cuoi;
  if not found then raise exception 'Hoá đơn % chưa có lần trả nợ nào để huỷ', h.ma using errcode = 'P0001'; end if;
  if c.ref is distinct from p_ref then raise exception 'Chỉ huỷ được dòng cuối cùng của lịch sử nợ. Tải lại trang rồi thử lại.' using errcode = 'P0001'; end if;
  if c.loai = 'tra_no' then
    select * into t from public.thanh_toan where id = c.ref::uuid;
    insert into public.thanh_toan (hoa_don_id, loai, phuong_thuc, so_tien, ngan_hang, loai_vi, ngay, nguoi_id, dao_cua_id, ghi_chu)
    values (p_id, 'hoan', t.phuong_thuc, t.so_tien, t.ngan_hang, t.loai_vi, t.ngay, p_nguoi, t.id,
            'Huỷ lần trả nợ PT' || t.so_phieu || coalesce(': ' || nullif(btrim(p_ly_do), ''), ''));
  else
    select * into x from public.hoa_don_dieu_chinh_no where id = c.ref::bigint;
    insert into public.hoa_don_dieu_chinh_no (hoa_don_id, loai, so_tien, ly_do, dao_cua_id, nguoi_id)
    values (p_id, 'huy_xoa_no', x.so_tien, coalesce(nullif(btrim(p_ly_do), ''), 'Huỷ lần xoá nợ'), x.id, p_nguoi);
    perform public.tinh_lai_hoa_don(p_id);
  end if;
end $$;
revoke all on function public.huy_lan_tra_no(uuid, text, uuid, text) from public, anon, authenticated;

