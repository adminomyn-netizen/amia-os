create table if not exists public.nhan_hieu (
  id uuid primary key default gen_random_uuid(),
  sh_id bigint unique,
  ten text not null check (length(btrim(ten)) between 1 and 120),
  ma_quoc_gia text,
  quoc_gia text,
  hoat_dong boolean not null default true,
  tao_luc timestamptz not null default now()
);
create unique index if not exists nhan_hieu_ten_khong_hoa on public.nhan_hieu (lower(btrim(ten)));
comment on table public.nhan_hieu is 'Danh mục nhãn hiệu (hãng) cho sản phẩm, như SalonHero listBrands. san_pham.nhan_hieu lưu tên hãng.';

